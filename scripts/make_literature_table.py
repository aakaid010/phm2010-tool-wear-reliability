"""Table 1 (literature) and its in-text counts, generated from data/literature.csv.

Each row of literature.csv records how one PHM2010 tool-wear study splits the cutters,
whether it reports an uncertainty estimate, and whether it evaluates interval coverage,
as read in the paper (column `source`: full text or abstract only; `evidence` quotes it).
Fields that could not be determined from the accessible text are "not reported".

  python make_literature_table.py --csv ../data/literature.csv --out <paper>/generated

Writes <out>/tab_literature.tex and <out>/lit_numbers.tex (macros \\litN... ).
"""
from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

WORDS = {0: "none", 1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven",
         8: "eight", 9: "nine", 10: "ten", 11: "eleven", 12: "twelve", 13: "thirteen",
         14: "fourteen", 15: "fifteen"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", default="../data/literature.csv")
    ap.add_argument("--out", default="../../manuscript/generated")
    a = ap.parse_args()
    d = pd.read_csv(a.csv).sort_values(["year", "key"], kind="stable")
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)

    rows = []
    for _, r in d.iterrows():
        dag = "$^\\dagger$" if r.source == "abstract" else ""
        cells = [str(c).replace("%", "\\%") for c in
                 (r.model, r.split, r.uncertainty, r.interval_coverage)]
        rows.append(f"\\citet{{{r.key}}}{dag} & " + " & ".join(cells) + " \\\\")
    this = ("This study & random forest; gradient boosting & PHM2010: cutter pairs (A$\\to$T); "
            "nine tools: leave-one-tool-out, leave-one-machine-out & Yes (split-conformal interval) "
            "& per held-out tool \\\\")
    col = ">{\\raggedright\\arraybackslash}p"
    tex = (
        "% AUTO-GENERATED by make_literature_table.py from data/literature.csv - do not edit\n"
        "\\begin{table*}[tbp]\n\\centering\\small\n"
        # widths sum to 0.89\linewidth; the 8 inter-column gaps (2 x 6 pt each) add ~0.095
        f"\\begin{{tabular}}{{@{{}}{col}{{0.16\\linewidth}} {col}{{0.20\\linewidth}} "
        f"{col}{{0.25\\linewidth}} {col}{{0.15\\linewidth}} {col}{{0.13\\linewidth}}@{{}}}}\n"
        "\\toprule\nStudy & Model & Split & Uncertainty reported & Per-cutter coverage evaluated \\\\\n"
        "\\midrule\n" + "\n".join(rows) + "\n\\midrule\n" + this + "\n\\bottomrule\n\\end{tabular}\n"
        "\\par\\smallskip\\parbox{\\linewidth}{\\footnotesize LOCO: leave-one-cutter-out (two of "
        "C1, C4 and C6 for training, the third for testing). Within-cutter: training and test cuts "
        "come from the same cutter. $^\\dagger$Full text not accessible; ``not reported'' means not "
        "reported in the abstract.}\n"
        "\\caption{PHM2010 tool-wear regression studies: how cutters are split between training and "
        "test data, whether an uncertainty estimate is reported, and whether interval coverage is "
        "evaluated per held-out cutter.}\n\\label{tab:literature}\n\\end{table*}\n")
    (out / "tab_literature.tex").write_text(tex, encoding="utf-8")

    n = len(d)
    held = int((d.split_class == "held_out").sum())
    uq = d.uncertainty.str.startswith("Yes")
    cov_any = d.interval_coverage.str.contains("pooled|per cutter") | (d.interval_coverage == "Yes")
    cov_per = int((d.interval_coverage == "per cutter").sum())
    macros = {
        "litN": n, "litHeldOut": held, "litUQ": int(uq.sum()),
        "litCovAny": int(cov_any.sum()), "litCovPerCutter": cov_per,
        "litAbstractOnly": int((d.source == "abstract").sum()),
        "litYearMin": int(d.year.min()), "litYearMax": int(d.year.max()),
    }
    lines = ["% AUTO-GENERATED by make_literature_table.py - do not edit"]
    for k, v in macros.items():
        lines.append(f"\\newcommand{{\\{k}}}{{{v}}}")
        if k in ("litN", "litHeldOut", "litUQ", "litCovAny", "litCovPerCutter"):
            lines.append(f"\\newcommand{{\\{k}Word}}{{{WORDS[v]}}}")
    (out / "lit_numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote tab_literature.tex and lit_numbers.tex:", macros)


if __name__ == "__main__":
    main()
